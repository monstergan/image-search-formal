-- 图搜查询日志表：记录每次以图搜图查询请求
CREATE TABLE IF NOT EXISTS `img_search_query_log` (
  `id` BIGINT NOT NULL COMMENT '主键ID',
  `query_no` VARCHAR(64) NOT NULL COMMENT '查询编号',
  `instance_id` BIGINT NOT NULL COMMENT '图搜实例ID',
  `biz_scene` VARCHAR(32) NOT NULL COMMENT '业务场景',
  `query_source` TINYINT NOT NULL COMMENT '查询来源：1上传文件 2图片URL 3OSS对象',
  `query_image_md5` CHAR(32) DEFAULT NULL COMMENT '查询图片的 MD5',
  `query_image_url` VARCHAR(1024) DEFAULT NULL COMMENT '查询图片地址',
  `threshold_score` DECIMAL(5,4) DEFAULT NULL COMMENT '相似度阈值',
  `top_k` INT NOT NULL DEFAULT 20 COMMENT '返回结果数量',
  `filter_expr` VARCHAR(1024) DEFAULT NULL COMMENT '传给阿里云的过滤表达式',
  `docs_found` INT DEFAULT NULL COMMENT '查询命中总数',
  `docs_return` INT DEFAULT NULL COMMENT '实际返回数量',
  `search_time_ms` INT DEFAULT NULL COMMENT '查询耗时，单位毫秒',
  `top1_product_id` VARCHAR(128) DEFAULT NULL COMMENT 'Top1 命中的 ProductId',
  `top1_pic_name` VARCHAR(128) DEFAULT NULL COMMENT 'Top1 命中的 PicName',
  `top1_score` DECIMAL(5,4) DEFAULT NULL COMMENT 'Top1 命中的相似度',
  `request_id` VARCHAR(64) DEFAULT NULL COMMENT '阿里云接口请求ID',
  `operator_id` BIGINT DEFAULT NULL COMMENT '操作人ID',
  `operator_name` VARCHAR(64) DEFAULT NULL COMMENT '操作人名称',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_query_no` (`query_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='图搜查询日志表';

